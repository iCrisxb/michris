let previouslyFocused = null;

function showModal(markup) {
  previouslyFocused = document.activeElement;
  const backdrop = $("#modalBackdrop");
  const content = $("#modalContent");

  content.innerHTML = markup;
  backdrop.classList.remove("hidden");
  backdrop.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";

  setTimeout(() => $("#modalClose")?.focus(), 50);
}

function closeModal() {
  const backdrop = $("#modalBackdrop");
  backdrop.classList.add("hidden");
  backdrop.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
  closeLightbox();
  if (previouslyFocused) previouslyFocused.focus();
}

function modalHeading(kicker, title, lead) {
  return `
    <span class="modal-kicker">${escapeHTML(kicker)}</span>
    <h2 class="modal-title" id="modalTitle">${escapeHTML(title)}</h2>
    <p class="modal-lead">${escapeHTML(lead)}</p>
  `;
}

